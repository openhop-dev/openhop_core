LOCAL_IDENTITY = LocalIdentity(bytes(32))
SENDER_IDENTITY = LocalIdentity(bytes([0x16]) + bytes(31))

# Generated by the local MeshCore checkout's src/Utils.cpp::encryptThenMAC
# using its bundled C++ Crypto AES-128/HMAC implementation. The full PATH
# payload is dest_hash(0x3B), src_hash(0x2E), then its MAC+ciphertext for the
# plaintext 00 03 78 56 34 12 02 A5 (empty path, 6-byte firmware ACK).
MESHCORE_PATH_ACK_PAYLOAD = bytes.fromhex("3b2eb6ac4f0aace10b1ff6a0fa1b0cc050797ec1")


def _path_return(
    local_identity,
    peer_identity,
    path,
    extra_type,
    extra,
    path_len_encoded=None,
):
    shared_secret = Identity(peer_identity.get_public_key()).calc_shared_secret(
        local_identity.get_private_key()
    )
    return PacketBuilder.create_path_return(
        dest_hash=local_identity.get_public_key()[0],
        src_hash=peer_identity.get_public_key()[0],
        secret=shared_secret,
        path=path,
        extra_type=extra_type,
        extra=extra,
        path_len_encoded=path_len_encoded,
    )


def _handler_with_pending_ack(local_identity, contacts, ack_crc):
    dispatcher = SimpleNamespace(
        local_identity=local_identity,
        contact_book=contacts,
        _waiting_acks={ack_crc: object()},
    )
    return AckHandler(lambda _message: None, dispatcher)


def _packet_with_encrypted_inner(local_identity, peer_identity, inner):
    shared_secret = Identity(peer_identity.get_public_key()).calc_shared_secret(
        local_identity.get_private_key()
    )
    packet = Packet()
    packet.header = (PAYLOAD_TYPE_PATH << 2) | ROUTE_TYPE_FLOOD
    packet.path_len = 0
    packet.path = bytearray()
    packet.payload = bytearray(
        bytes([local_identity.get_public_key()[0], peer_identity.get_public_key()[0]])
        + CryptoUtils.encrypt_then_mac(shared_secret[:16], shared_secret, inner)
    )
    packet.payload_len = len(packet.payload)
    return packet


class _CallbackRadio:
    def set_rx_callback(self, callback):
        self.rx_callback = callback


@pytest.mark.asyncio
async def test_path_ack_tries_later_colliding_contact_after_mac_failure():
    """A valid PATH ACK must survive a one-byte source-hash collision."""
    local_identity = LOCAL_IDENTITY
    decoy = LocalIdentity(bytes([0x0C]) + bytes(31))
    sender = SENDER_IDENTITY
    assert decoy.get_public_key()[0] == sender.get_public_key()[0]

    contacts = ContactStore()
    contacts.add(Contact(public_key=decoy.get_public_key(), name="Decoy"))
    contacts.add(Contact(public_key=sender.get_public_key(), name="Sender"))
    ack_crc = 0x12345678
    packet = _path_return(
        local_identity,
        sender,
        path=[],
        extra_type=PAYLOAD_TYPE_ACK,
        extra=ack_crc.to_bytes(4, "little"),
    )
    assert len(packet.payload) == 20

    handler = _handler_with_pending_ack(local_identity, contacts, ack_crc)
    assert await handler.process_path_ack_variants(packet) == ack_crc


