@pytest.mark.asyncio
async def test_path_ack_rejects_wrong_destination_unknown_source_bad_mac_and_path_len():
    """Only an addressed, authenticated, well-formed PATH ACK may resolve a send."""
    contacts = ContactStore()
    contacts.add(Contact(public_key=SENDER_IDENTITY.get_public_key(), name="Sender"))
    ack_crc = 0x12345678

    wrong_destination = _path_return(
        LOCAL_IDENTITY,
        SENDER_IDENTITY,
        path=[],
        extra_type=PAYLOAD_TYPE_ACK,
        extra=ack_crc.to_bytes(4, "little"),
    )
    wrong_destination.payload[0] ^= 0xFF
    assert (
        await _handler_with_pending_ack(
            LOCAL_IDENTITY, contacts, ack_crc
        ).process_path_ack_variants(wrong_destination)
        is None
    )

    unknown_source = _path_return(
        LOCAL_IDENTITY,
        SENDER_IDENTITY,
        path=[],
        extra_type=PAYLOAD_TYPE_ACK,
        extra=ack_crc.to_bytes(4, "little"),
    )
    assert (
        await _handler_with_pending_ack(
            LOCAL_IDENTITY, ContactStore(), ack_crc
        ).process_path_ack_variants(unknown_source)
        is None
    )

    bad_mac = _path_return(
        LOCAL_IDENTITY,
        SENDER_IDENTITY,
        path=[],
        extra_type=PAYLOAD_TYPE_ACK,
        extra=ack_crc.to_bytes(4, "little"),
    )
    bad_mac.payload[-1] ^= 0x01
    assert (
        await _handler_with_pending_ack(
            LOCAL_IDENTITY, contacts, ack_crc
        ).process_path_ack_variants(bad_mac)
        is None
    )

    invalid_path_len = _packet_with_encrypted_inner(
        LOCAL_IDENTITY,
        SENDER_IDENTITY,
        b"\xc0" + bytes([PAYLOAD_TYPE_ACK]) + ack_crc.to_bytes(4, "little"),
    )
    assert (
        await _handler_with_pending_ack(
            LOCAL_IDENTITY, contacts, ack_crc
        ).process_path_ack_variants(invalid_path_len)
        is None
    )

    truncated_path = _packet_with_encrypted_inner(
        LOCAL_IDENTITY,
        SENDER_IDENTITY,
        bytes([PathUtils.encode_path_len(1, 63)]) + bytes(15),
    )
    assert (
        await _handler_with_pending_ack(
            LOCAL_IDENTITY, contacts, ack_crc
        ).process_path_ack_variants(truncated_path)
        is None
    )


@pytest.mark.asyncio
async def test_path_handler_updates_matched_contact_sends_reciprocal_and_resolves_waiter():
    """The full Core PATH flow mirrors MeshCore's path update and ACK completion."""
    decoy = LocalIdentity(bytes([0x0C]) + bytes(31))
    contacts = ContactStore()
    contacts.add(Contact(public_key=decoy.get_public_key(), name="Decoy"))
    contacts.add(Contact(public_key=SENDER_IDENTITY.get_public_key(), name="Sender"))
    ack_crc = 0x12345678
    out_path = bytes([0xA1, 0xB2])
    encoded_out_path_len = PathUtils.encode_path_len(1, 2)
    packet = _path_return(
        LOCAL_IDENTITY,
        SENDER_IDENTITY,
        path=out_path,
        extra_type=PAYLOAD_TYPE_ACK,
        extra=ack_crc.to_bytes(4, "little") + b"\x02\xa5",
        path_len_encoded=encoded_out_path_len,
    )
    packet.set_path(b"\xc3", PathUtils.encode_path_len(1, 1))

    dispatcher = Dispatcher(_CallbackRadio())
    dispatcher.local_identity = LOCAL_IDENTITY
    dispatcher.set_contact_book(contacts)
    waiting = asyncio.Event()
    dispatcher._waiting_acks[ack_crc] = waiting

    ack_handler = AckHandler(lambda _message: None, dispatcher)
    ack_handler.set_ack_received_callback(dispatcher._register_ack_received)
    response_handler = ProtocolResponseHandler(lambda _message: None, LOCAL_IDENTITY, contacts)
    sent_reciprocals = []

    async def inject(packet_to_send):
        sent_reciprocals.append(packet_to_send)

    response_handler.set_packet_injector(inject)
    result = await PathHandler(
        lambda _message: None,
        ack_handler=ack_handler,
        protocol_response_handler=response_handler,
    )(packet)
    await response_handler.wait_for_pending_reciprocals()

    assert result.authenticated is True
    assert waiting.is_set()
    assert ack_crc not in dispatcher._waiting_acks
    assert contacts.get_by_key(SENDER_IDENTITY.get_public_key()).out_path == out_path
    assert contacts.get_by_key(decoy.get_public_key()).out_path == b""
    assert len(sent_reciprocals) == 1
    reciprocal = sent_reciprocals[0]
    assert reciprocal.is_route_direct()
    assert reciprocal.path_len == encoded_out_path_len
    assert bytes(reciprocal.path) == out_path
    assert reciprocal.payload[:2] == bytes(
        [SENDER_IDENTITY.get_public_key()[0], LOCAL_IDENTITY.get_public_key()[0]]
    )
    shared_secret = Identity(SENDER_IDENTITY.get_public_key()).calc_shared_secret(
        LOCAL_IDENTITY.get_private_key()
    )
    reciprocal_inner = CryptoUtils.mac_then_decrypt(
        shared_secret[:16], shared_secret, bytes(reciprocal.payload[2:])
    )
    assert reciprocal_inner[:3] == bytes([PathUtils.encode_path_len(1, 1), 0xC3, 0xFF])


@pytest.mark.asyncio
async def test_path_embedded_ack_notifies_listener_without_dispatcher_waiters():
    """Companion flow: the app (not the dispatcher) tracks expected ACK CRCs.

    Firmware Mesh::onRecvPacket decrypts every PATH addressed to this node and
    hands its extra (the embedded ACK for a flood text message) to processAck —
    with no dispatcher-level waiting-ack precondition. The PATH-embedded ACK
    must therefore reach the ack-received listener even when _waiting_acks is
    empty, or a companion client never sees delivery confirmation for a flood DM.
    """
    contacts = ContactStore()
    contacts.load_from([Contact(public_key=SENDER_IDENTITY.get_public_key(), name="peer")])
    ack_crc = 0x12345678
    dispatcher = SimpleNamespace(
        local_identity=LOCAL_IDENTITY,
        contact_book=contacts,
        _waiting_acks={},  # companion: nothing waits at dispatcher level
    )
    handler = AckHandler(lambda _message: None, dispatcher)

    notified = []

    async def listener(crc):
        notified.append(crc)

    handler.set_ack_received_callback(listener)

    packet = _path_return(
        LOCAL_IDENTITY,
        SENDER_IDENTITY,
        path=[],
        extra_type=PAYLOAD_TYPE_ACK,
        extra=ack_crc.to_bytes(4, "little"),
    )
    found = await handler.process_path_ack_variants(packet)
    assert found == ack_crc
    await handler._notify_ack_received(found)
    assert notified == [ack_crc]


